const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {getExampleCards,countOwnedSpecies,finishKeys}=require('../native/lib/example-cards');
const root=path.join(__dirname,'..');
const cards=getExampleCards();
assert.equal(cards.length,0);
assert.equal(new Set(cards.map(card=>card.speciesId)).size,0);
assert.ok(cards.every(card=>card.kind==='example'&&card.readOnly&&card.sample&&card.sourceLabel==='示例卡 · 非本人拍摄'));
assert.deepEqual(cards,[]);
assert.deepEqual(Object.keys(finishKeys),[]);
assert.equal(countOwnedSpecies(cards),0,'example cards cannot affect owned species totals');
assert.equal(countOwnedSpecies([{kind:'example',speciesId:'ibis'},{id:'real',speciesId:'ibis'},{id:'other',speciesId:'moth'}]),2);
const home=fs.readFileSync(path.join(root,'native/pages/home/index.wxml'),'utf8');
const homeJs=fs.readFileSync(path.join(root,'native/pages/home/index.js'),'utf8');
const library=fs.readFileSync(path.join(root,'native/pages/library/index.wxml'),'utf8');
const libraryJs=fs.readFileSync(path.join(root,'native/pages/library/index.js'),'utf8');
const cardJs=fs.readFileSync(path.join(root,'native/pages/card/index.js'),'utf8');
const cardWxml=fs.readFileSync(path.join(root,'native/pages/card/index.wxml'),'utf8');
assert.ok(!homeJs.includes('getExampleCards'),'home personal progress does not inject examples');
assert.ok(!library.includes('博物志案例')&&!library.includes('bindtap="openExample"'),'collection is real only');
assert.ok(!libraryJs.includes('getExampleCards'),'example data remains available but is not injected into collection');
assert.ok(cardJs.includes("this.data.isSample")&&cardJs.includes('示例卡不可导出为我的卡'));
assert.ok(cardWxml.includes('不计入你的真实收藏'));
assert.ok(libraryJs.includes('realCards(app.getCards())'),'library uses shared real-only model');
assert.ok(fs.readFileSync(path.join(root,'native/pages/profile/index.js'),'utf8').includes('realCards(app.getCards())'),'profile uses shared real-only model');
assert.match(fs.readFileSync(path.join(root,'native/pages/settings/index.js'),'utf8'),/kind!==['"]example['"]&&![a-z]+\.sample/,'legacy samples are excluded from settings');
console.log('PASS: retired launch examples are absent but excluded from personal collection and export');
